// SQLite -> Postgres DDL translation helper (S5-PLT-01 spike). Pure string functions: no pg driver, no network.
// Covers only the constructs found in this repo's migrations (see architecture/spikes/cloud-sql-store.md).

/** Replace `?` placeholders with $1, $2, ... outside single-quoted string literals. */
export function translatePlaceholders(sql) {
  let n = 0;
  let out = '';
  let inStr = false;
  for (let i = 0; i < sql.length; i++) {
    const c = sql[i];
    if (c === "'") { if (inStr && sql[i + 1] === "'") { out += "''"; i++; continue; } inStr = !inStr; }
    out += !inStr && c === '?' ? `$${++n}` : c;
  }
  return out;
}

/**
 * Translate a SQLite migration script to Postgres.
 * - PRAGMA statements are dropped.
 * - `x INTEGER PRIMARY KEY AUTOINCREMENT` becomes `x BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY`.
 * - Correlated ROW_NUMBER backfill (UPDATE t SET c = (SELECT x.rn FROM (...) x WHERE x.oid = t.id)) becomes UPDATE ... FROM.
 * - rowid becomes an explicit `_rowid` identity column, added with a prelude ALTER TABLE.
 * - RAISE(ABORT) triggers become a plpgsql function plus trigger.
 * - `?` placeholders become $n.
 * @param {string} sql
 * @returns {string}
 */
export function translateToPostgres(sql) {
  let s = String(sql);
  s = s.replace(/\bPRAGMA\s+[^;]*;?/gi, '');
  s = s.replace(/(\w+)\s+INTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT/gi, '$1 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  s = s.replace(
    /UPDATE\s+(\w+)\s+SET\s+(\w+)\s*=\s*\(\s*SELECT\s+x\.(\w+)\s+FROM\s*\(\s*(SELECT\s+\w+\s+AS\s+oid,[\s\S]*?FROM\s+\1)\s*\)\s*x\s+WHERE\s+x\.oid\s*=\s*\1\.id\s*\)\s*;/gi,
    'UPDATE $1 SET $2 = x.$3 FROM ($4) x WHERE x.oid = $1.id;',
  );
  s = s.replace(
    /CREATE\s+TRIGGER\s+IF\s+NOT\s+EXISTS\s+(\w+)\s+BEFORE\s+(UPDATE|DELETE)\s+ON\s+(\w+)\s*BEGIN\s+SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*'([^']*)'\s*\)\s*;\s*END;?/gi,
    (_m, name, op, table, msg) => `CREATE OR REPLACE FUNCTION ${name}_fn() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION '${msg}'; END $$;\n`
      + `DROP TRIGGER IF EXISTS ${name} ON ${table};\nCREATE TRIGGER ${name} BEFORE ${op} ON ${table} FOR EACH ROW EXECUTE FUNCTION ${name}_fn();`,
  );
  if (/\browid\b/i.test(s)) {
    const t = /\browid\b[\s\S]*?\bFROM\s+(\w+)/i.exec(s);
    if (!t) throw new Error('rowid used but its table could not be determined');
    s = s.replace(/\browid\b/gi, '_rowid');
    s = `ALTER TABLE ${t[1]} ADD COLUMN IF NOT EXISTS _rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;\n${s}`;
  }
  s = translatePlaceholders(s);
  return s.replace(/\n{3,}/g, '\n\n').trim();
}
