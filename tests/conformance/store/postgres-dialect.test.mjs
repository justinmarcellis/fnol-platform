// Pure string translation of the repo's real SQLite migrations to Postgres DDL. No pg driver, no network.
import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { translateToPostgres, translatePlaceholders } from './dialect.mjs';
import { migrations as busMigrations } from '../../../src/core/bus.mjs';
import { migrations as auditMigrations } from '../../../src/core/audit.mjs';
import { migrations as webhookMigrations } from '../../../src/modules/integrations/webhooks/migrations.mjs';

const sqlOf = (m) => (typeof m === 'string' ? m : m.sql);
const all = [...busMigrations, ...auditMigrations, ...webhookMigrations].map(sqlOf);

describe('translateToPostgres on real migrations', () => {
  it('has no SQLite-only constructs left in any real migration', () => {
    for (const sql of all) {
      const pg = translateToPostgres(sql);
      assert.doesNotMatch(pg, /\bPRAGMA\b/i);
      assert.doesNotMatch(pg, /\bAUTOINCREMENT\b/i);
      assert.doesNotMatch(pg, /\browid\b/i);
      assert.doesNotMatch(pg, /RAISE\s*\(\s*ABORT/i);
      assert.doesNotMatch(pg, /\?/);
    }
  });

  it('drops PRAGMA statements (as issued by store.mjs on open)', () => {
    const out = translateToPostgres('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;\nSELECT 1;');
    assert.equal(out, 'SELECT 1;');
  });

  it('turns INTEGER PRIMARY KEY AUTOINCREMENT into an identity column', () => {
    const wh = translateToPostgres(sqlOf(webhookMigrations[0]));
    assert.match(wh, /seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
    assert.match(wh, /CREATE TABLE IF NOT EXISTS webhook_subscriptions/);
    assert.match(wh, /CREATE INDEX IF NOT EXISTS idx_webhook_subs_tenant/);
  });

  it('rewrites the outbox seq backfill (ROW_NUMBER + rowid) to UPDATE ... FROM with an explicit column', () => {
    const seq = busMigrations.map(sqlOf).find((s) => /ROW_NUMBER/.test(s));
    assert.ok(seq, 'found the real backfill migration in bus.mjs');
    const pg = translateToPostgres(seq);
    assert.match(pg, /^ALTER TABLE outbox ADD COLUMN IF NOT EXISTS _rowid BIGINT GENERATED BY DEFAULT AS IDENTITY;/);
    assert.match(pg, /ALTER TABLE outbox ADD COLUMN seq INTEGER;/);
    assert.match(pg, /UPDATE outbox SET seq = x\.rn FROM \(SELECT id AS oid, ROW_NUMBER\(\) OVER \(PARTITION BY tenant_id ORDER BY created_at, _rowid\) AS rn FROM outbox\) x WHERE x\.oid = outbox\.id;/);
    assert.doesNotMatch(pg, /SET seq = \(\s*SELECT/);
    assert.match(pg, /CREATE UNIQUE INDEX IF NOT EXISTS idx_outbox_tenant_seq ON outbox \(tenant_id, seq\)/);
  });

  it('converts the append-only audit triggers to plpgsql functions and triggers', () => {
    const pg = translateToPostgres(auditMigrations.map(sqlOf).join('\n'));
    assert.match(pg, /CREATE OR REPLACE FUNCTION audit_log_no_update_fn\(\) RETURNS trigger LANGUAGE plpgsql AS \$\$ BEGIN RAISE EXCEPTION 'audit_log is append-only'; END \$\$;/);
    assert.match(pg, /CREATE TRIGGER audit_log_no_delete BEFORE DELETE ON audit_log FOR EACH ROW EXECUTE FUNCTION audit_log_no_delete_fn\(\);/);
  });

  it('leaves portable DDL unchanged apart from the translated parts', () => {
    const outbox = translateToPostgres(sqlOf(busMigrations[0]));
    assert.match(outbox, /CREATE TABLE IF NOT EXISTS outbox/);
  });
});

describe('placeholders', () => {
  it('numbers ? as $n and ignores ? inside string literals', () => {
    assert.equal(
      translatePlaceholders("SELECT * FROM t WHERE a = ? AND b = 'what?' AND c IN (?, ?) AND d = 'it''s ?'"),
      "SELECT * FROM t WHERE a = $1 AND b = 'what?' AND c IN ($2, $3) AND d = 'it''s ?'",
    );
  });
  it('applies through translateToPostgres', () => {
    assert.equal(translateToPostgres('UPDATE outbox SET status = ? WHERE id = ?'), 'UPDATE outbox SET status = $1 WHERE id = $2');
  });
  it('throws when rowid is used without a determinable table', () => {
    assert.throws(() => translateToPostgres('SELECT rowid'), /rowid/);
  });
});
