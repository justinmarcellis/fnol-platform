/** Register every CSR table with the shared i18n registry. */
export function registerCsrStrings(registerStrings) {
  for (const [locale, table] of Object.entries(csrStrings)) registerStrings(locale, table);
}

/** Minimal translator for tests and fallbacks (no kit needed). */
export function makeT(locale = 'en') {
  return (key, params = {}) => {
    const s = csrStrings[locale]?.[key] ?? csrStrings.en[key] ?? key;
    return s.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
  };
}
